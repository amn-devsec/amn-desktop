export const DICTIONNAIRES_CONNECTEURS: Record<Langue, Record<CleConnecteurs, string>> = { en: EN, fr: FR };

/** Le mot, avec ses `{variables}` remplacées. */
export function traduireConnecteurs(langue: Langue, cle: CleConnecteurs, vars: Record<string, string | number> = {}): string {
  const brut = DICTIONNAIRES_CONNECTEURS[langue][cle] ?? EN[cle];
  return brut.replace(/\{(\w+)\}/g, (tout, nom: string) => (nom in vars ? String(vars[nom]) : tout));
}
