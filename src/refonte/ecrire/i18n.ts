const mots = definirMots(EN, FR);
export const useMotsEcrire = mots.useMots;
export const DICTIONNAIRES_ECRIRE = mots.dictionnaires;
export type CleEcrire = keyof typeof EN;

export function dire(langue: Langue, cle: CleEcrire, params?: ParamsMots): string {
  return mots.traduire(langue, cle, params);
}

/** `<base>.1` pour 0 et 1, `<base>.n` au-delà (usage français). */
export function direCompte(langue: Langue, base: string, n: number, params: ParamsMots = {}): string {
  const cle = `${base}.${n <= 1 ? '1' : 'n'}` as CleEcrire;
  return dire(langue, cle, { n, ...params });
}
