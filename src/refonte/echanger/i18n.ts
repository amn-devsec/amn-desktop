const mots = definirMots(EN, FR);
export const useMotsEchanger = mots.useMots;
export const DICTIONNAIRES_ECHANGER = mots.dictionnaires;
export type CleEchanger = keyof typeof EN;

export function dire(langue: Langue, cle: CleEchanger, params?: ParamsMots): string {
  return mots.traduire(langue, cle, params);
}

/** `<base>.1` pour 0 et 1, `<base>.n` au-delà (usage français). */
export function direCompte(langue: Langue, base: string, n: number, params: ParamsMots = {}): string {
  const cle = `${base}.${n <= 1 ? '1' : 'n'}` as CleEchanger;
  return dire(langue, cle, { n, ...params });
}
